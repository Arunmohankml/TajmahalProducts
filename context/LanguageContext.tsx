interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (code: LanguageCode) => void;
  currentOption: LanguageOption;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("tm_language") as LanguageCode;
      if (saved && TRANSLATIONS[saved]) {
        setLanguageState(saved);
        applyGoogleTranslate(saved);
      }
    } catch (e) {}
  }, []);

  const applyGoogleTranslate = (code: LanguageCode) => {
    if (typeof window === "undefined") return;

    try {
      // 1. Set Google Translate cookie so the whole page translates automatically
      const cookieVal = code === "en" ? "/en/en" : `/en/${code}`;
      document.cookie = `googtrans=${cookieVal}; path=/;`;
      const domain = window.location.hostname;
      if (domain && domain !== "localhost" && !domain.includes("127.0.0.1")) {
        document.cookie = `googtrans=${cookieVal}; path=/; domain=.${domain};`;
      }

      // 2. Trigger Google Translate combo element if loaded in DOM
      const combo = document.querySelector<HTMLSelectElement>(".goog-te-combo");
      if (combo) {
        combo.value = code;
        combo.dispatchEvent(new Event("change"));
      }
    } catch (err) {}
  };

  const setLanguage = (code: LanguageCode) => {
    setLanguageState(code);
    try {
      localStorage.setItem("tm_language", code);
      if (typeof document !== "undefined") {
        document.documentElement.lang = code;
        document.documentElement.dir = code === "ar" ? "rtl" : "ltr";
        applyGoogleTranslate(code);
      }
    } catch (e) {}
  };

  const currentOption = LANGUAGES.find((l) => l.code === language) || LANGUAGES[0];

  const t = (key: string, fallback?: string): string => {
    const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
    if (dict && dict[key]) {
      return dict[key];
    }
    return fallback || TRANSLATIONS.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, currentOption, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      language: "en" as LanguageCode,
      setLanguage: () => {},
      currentOption: LANGUAGES[0],
      t: (k: string, fallback?: string) => fallback || k,
    };
  }
  return context;
}
